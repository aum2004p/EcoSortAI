"""
EcoSort AI - Dataset Preparation
=================================
Prepares datasets for training both models.

Model 1 (YOLO): Uses TrashNet + RealWaste images, converts to YOLO format
  - Creates a data.yaml config file
  - Organizes images into train/val/test splits
  - Converts bounding box annotations to YOLO format

Model 2 (CNN): Uses custom-labeled clean/contaminated images
  - Organizes into train/val/test splits
  - Creates a directory structure for PyTorch ImageFolder

Usage:
    python training/prepare_dataset.py --mode yolo --source /path/to/datasets
    python training/prepare_dataset.py --mode cnn  --source /path/to/quality_images
"""

import os
import sys
import argparse
import shutil
import random
from pathlib import Path

# Add project root to path
PROJECT_ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(PROJECT_ROOT))


def prepare_yolo_dataset(source_dir, output_dir, train_ratio=0.7, val_ratio=0.2):
    """
    Prepare a YOLO-format dataset from image directories.

    Expected source structure:
        source_dir/
            trashnet/
                glass/       (images of glass)
                paper/
                plastic/
                ...
            realwaste/
                cardboard/
                ...

    The script will:
    1. Create train/val/test splits
    2. Write a data.yaml config file for ultralytics YOLO
    """
    output_dir = Path(output_dir)
    images_train = output_dir / 'images' / 'train'
    images_val = output_dir / 'images' / 'val'
    images_test = output_dir / 'images' / 'test'
    labels_train = output_dir / 'labels' / 'train'
    labels_val = output_dir / 'labels' / 'val'
    labels_test = output_dir / 'labels' / 'test'

    for d in [images_train, images_val, images_test,
              labels_train, labels_val, labels_test]:
        d.mkdir(parents=True, exist_ok=True)

    # Waste class to YOLO class index
    class_map = {
        'glass': 0, 'paper': 1, 'plastic': 2,
        'cardboard': 3, 'metal': 4, 'trash': 5,
    }

    # Gather all images and their categories
    all_images = []
    source = Path(source_dir)
    for dataset_dir in source.iterdir():
        if not dataset_dir.is_dir():
            continue
        for category_dir in dataset_dir.iterdir():
            if not category_dir.is_dir():
                continue
            category = category_dir.name.lower().strip()
            if category not in class_map:
                print(f"  Skipping unknown category: {category}")
                continue
            for img_file in category_dir.iterdir():
                if img_file.suffix.lower() in ['.jpg', '.jpeg', '.png']:
                    all_images.append((img_file, class_map[category]))

    if not all_images:
        print(f"No images found in {source_dir}")
        return

    random.shuffle(all_images)
    n = len(all_images)
    n_train = int(n * train_ratio)
    n_val = int(n * val_ratio)

    splits = {
        'train': all_images[:n_train],
        'val': all_images[n_train:n_train + n_val],
        'test': all_images[n_train + n_val:],
    }

    for split_name, items in splits.items():
        img_dir = output_dir / 'images' / split_name
        lbl_dir = output_dir / 'labels' / split_name
        for img_path, class_idx in items:
            # Copy image
            shutil.copy2(img_path, img_dir / img_path.name)
            # Write label file (full-image bounding box as a starting point)
            # YOLO format: class x_center y_center width height (normalized 0-1)
            label_path = lbl_dir / (img_path.stem + '.txt')
            with open(label_path, 'w') as f:
                # Full image bounding box: center=(0.5,0.5), size=(1,1)
                f.write(f"{class_idx} 0.5 0.5 1.0 1.0\n")

    # Write data.yaml
    yaml_content = f"""# EcoSort AI - YOLO Dataset Configuration
# Auto-generated by prepare_dataset.py

path: {output_dir.resolve()}
train: images/train
val: images/val
test: images/test

# Class names (must match config.py WASTE_CATEGORIES)
names:
  0: glass
  1: paper
  2: plastic
  3: cardboard
  4: metal
  5: trash
"""
    yaml_path = output_dir / 'data.yaml'
    with open(yaml_path, 'w') as f:
        f.write(yaml_content)

    print(f"\nYOLO dataset prepared:")
    print(f"  Total images: {n}")
    print(f"  Train: {len(splits['train'])}")
    print(f"  Val:   {len(splits['val'])}")
    print(f"  Test:  {len(splits['test'])}")
    print(f"  Config: {yaml_path}")
    print(f"\nNote: Bounding boxes use full-image as placeholder.")
    print(f"      Use a labeling tool (e.g., LabelImg, CVAT) to draw")
    print(f"      accurate bounding boxes for actual training.")


def prepare_cnn_dataset(source_dir, output_dir, train_ratio=0.7, val_ratio=0.2):
    """
    Prepare a CNN classification dataset (clean/contaminated).

    Expected source structure:
        source_dir/
            clean/         (images of clean waste)
            contaminated/  (images of contaminated waste)

    Creates train/val/test splits with class subdirectories.
    """
    output_dir = Path(output_dir)
    classes = ['clean', 'contaminated']

    for split in ['train', 'val', 'test']:
        for cls in classes:
            (output_dir / split / cls).mkdir(parents=True, exist_ok=True)

    source = Path(source_dir)
    for cls in classes:
        cls_dir = source / cls
        if not cls_dir.exists():
            print(f"  Warning: {cls_dir} not found")
            continue

        images = [f for f in cls_dir.iterdir()
                  if f.suffix.lower() in ['.jpg', '.jpeg', '.png']]
        if not images:
            continue

        random.shuffle(images)
        n = len(images)
        n_train = int(n * train_ratio)
        n_val = int(n * val_ratio)

        splits = {
            'train': images[:n_train],
            'val': images[n_train:n_train + n_val],
            'test': images[n_train + n_val:],
        }

        for split_name, split_images in splits.items():
            for img in split_images:
                shutil.copy2(img, output_dir / split_name / cls / img.name)

        print(f"  {cls}: {len(images)} images "
              f"(train={len(splits['train'])}, val={len(splits['val'])}, "
              f"test={len(splits['test'])})")

    print(f"\nCNN dataset prepared at: {output_dir}")
    print(f"  Structure: {output_dir}/[train|val|test]/[clean|contaminated]/")


if __name__ == '__main__':
    parser = argparse.ArgumentParser(
        description='Prepare datasets for EcoSort AI training')
    parser.add_argument('--mode', choices=['yolo', 'cnn'], required=True,
                        help='Which model dataset to prepare')
    parser.add_argument('--source', required=True,
                        help='Source directory containing raw datasets')
    parser.add_argument('--output', default=None,
                        help='Output directory (default: data/<mode>_dataset)')
    args = parser.parse_args()

    random.seed(42)  # reproducible splits

    output = args.output or os.path.join(
        str(PROJECT_ROOT), 'data', f'{args.mode}_dataset')

    if args.mode == 'yolo':
        prepare_yolo_dataset(args.source, output)
    else:
        prepare_cnn_dataset(args.source, output)
